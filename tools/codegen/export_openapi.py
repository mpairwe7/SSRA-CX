#!/usr/bin/env python3
"""Export OpenAPI 3.1 contract snapshot from services/api and generate packages/api-client."""

from __future__ import annotations

import hashlib
import json
import subprocess
from pathlib import Path

from ssra_api import create_api_app

ROOT = Path(__file__).resolve().parents[2]
OPENAPI_OUT = ROOT / "services" / "api" / "openapi.json"
TS_CLIENT_OUT = ROOT / "packages" / "api-client" / "src" / "index.ts"


def main() -> None:
    app = create_api_app()
    spec = app.openapi()
    canonical = json.dumps(spec, indent=2, sort_keys=True) + "\n"
    OPENAPI_OUT.write_text(canonical, encoding="utf-8")
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()

    paths = sorted(spec.get("paths", {}).keys())
    path_literals = ",\n  ".join(f'"{p}"' for p in paths)

    ts_code = f"""// AUTO-GENERATED by tools/codegen/export_openapi.py — DO NOT EDIT MANUALLY.
// OpenAPI 3.1 contract SHA-256: {digest}

import {{ z }} from "zod";

export const OPENAPI_CONTRACT_SHA256 = "{digest}" as const;

export const ApiEndpointPaths = [
  {path_literals}
] as const;

export type ApiEndpointPath = (typeof ApiEndpointPaths)[number];

export const CreateConversationRequestSchema = z.object({{
  channel: z.string().default("web"),
  locale: z.string().default("en"),
}});
export type CreateConversationRequest = z.infer<typeof CreateConversationRequestSchema>;

export const ConversationResponseSchema = z.object({{
  id: z.string(),
  channel: z.string(),
  locale: z.string(),
  auth_level: z.string(),
  status: z.string(),
}});
export type ConversationResponse = z.infer<typeof ConversationResponseSchema>;

export const ActiveSnapshotResponseSchema = z.object({{
  version: z.string(),
  status: z.string(),
  approved_by: z.string(),
  checksum: z.string(),
}});
export type ActiveSnapshotResponse = z.infer<typeof ActiveSnapshotResponseSchema>;
"""
    TS_CLIENT_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_CLIENT_OUT.write_text(ts_code, encoding="utf-8")
    subprocess.run(["npx", "biome", "check", "--write", str(TS_CLIENT_OUT)], check=True)  # noqa: S603, S607
    print(
        f"Exported OpenAPI 3.1 ({digest[:16]}...) -> {OPENAPI_OUT.relative_to(ROOT)} & {TS_CLIENT_OUT.relative_to(ROOT)}"
    )


if __name__ == "__main__":
    main()
